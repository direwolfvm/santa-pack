-- Baseline for new Santa Pack installations.
-- Existing deployments should diff this file against the live project before applying it.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user', 'manager', 'admin')),
  role_pending text check (role_pending in ('manager', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.family (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 120),
  created_at timestamptz not null default now()
);

create table if not exists public.person (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 120),
  user_profile uuid not null unique references public.profiles(id) on delete cascade,
  family bigint constraint person_family_fkey references public.family(id) on delete set null,
  family_pending bigint references public.family(id) on delete set null,
  created_at timestamptz not null default now(),
  check (family is null or family_pending is null)
);

create table if not exists public.gift_round (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 120),
  family bigint not null references public.family(id) on delete cascade,
  stage text not null default 'giving' check (stage in ('giving', 'guessing', 'complete')),
  created_at timestamptz not null default now()
);

create table if not exists public.present (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 120),
  description text not null default '',
  cloaked_name text not null default '',
  giver bigint not null references public.person(id) on delete cascade,
  receiver bigint not null references public.person(id) on delete cascade,
  gift_round bigint not null references public.gift_round(id) on delete cascade,
  receiver_guess bigint references public.person(id) on delete set null,
  revealed boolean not null default false,
  created_at timestamptz not null default now(),
  unique (gift_round, giver, receiver),
  check (giver <> receiver)
);

create index if not exists person_family_idx on public.person(family);
create index if not exists person_family_pending_idx on public.person(family_pending);
create index if not exists gift_round_family_idx on public.gift_round(family);
create index if not exists present_round_idx on public.present(gift_round);
create index if not exists present_giver_receiver_idx on public.present(giver, receiver);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from profiles where id = auth.uid() and role = 'admin') $$;

create or replace function public.is_family_member(target_family bigint)
returns boolean language sql stable security definer set search_path = public
as $$ select exists (select 1 from person where user_profile = auth.uid() and family = target_family) $$;

create or replace function public.can_manage_family(target_family bigint)
returns boolean language sql stable security definer set search_path = public
as $$
  select public.is_admin() or exists (
    select 1 from person p join profiles pr on pr.id = p.user_profile
    where p.user_profile = auth.uid() and p.family = target_family and pr.role = 'manager'
  )
$$;

revoke all on function public.is_admin() from public;
revoke all on function public.is_family_member(bigint) from public;
revoke all on function public.can_manage_family(bigint) from public;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_family_member(bigint) to authenticated;
grant execute on function public.can_manage_family(bigint) to authenticated;

alter table public.profiles enable row level security;
alter table public.family enable row level security;
alter table public.person enable row level security;
alter table public.gift_round enable row level security;
alter table public.present enable row level security;

create policy "profiles read own or admin" on public.profiles for select to authenticated
  using (id = auth.uid() or public.is_admin());
create policy "profiles create own user row" on public.profiles for insert to authenticated
  with check (id = auth.uid() and role = 'user' and role_pending is null);
create policy "profiles update own request or admin" on public.profiles for update to authenticated
  using (id = auth.uid() or public.is_admin())
  with check (public.is_admin() or id = auth.uid());

create or replace function public.protect_profile_role()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.role is distinct from old.role and not public.is_admin() then
    raise exception 'Only administrators can change roles';
  end if;
  return new;
end
$$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role before update on public.profiles
  for each row execute procedure public.protect_profile_role();
revoke all on function public.protect_profile_role() from public;

create policy "families visible to signed in users" on public.family for select to authenticated using (true);
create policy "admins create families" on public.family for insert to authenticated with check (public.is_admin());
create policy "admins update families" on public.family for update to authenticated using (public.is_admin());
create policy "admins delete families" on public.family for delete to authenticated using (public.is_admin());

create policy "people visible to signed in users" on public.person for select to authenticated using (true);
create policy "users create their person" on public.person for insert to authenticated
  with check (user_profile = auth.uid() and family is null);
create policy "people update self or family manager" on public.person for update to authenticated
  using (user_profile = auth.uid() or public.can_manage_family(coalesce(family, family_pending)))
  with check (user_profile = auth.uid() or public.can_manage_family(coalesce(family, family_pending)));
create policy "admins delete people" on public.person for delete to authenticated using (public.is_admin());

create or replace function public.protect_person_membership()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if new.family is distinct from old.family
    and not public.can_manage_family(coalesce(old.family, new.family, old.family_pending, new.family_pending)) then
    raise exception 'Only a family manager can change approved membership';
  end if;
  return new;
end
$$;

drop trigger if exists protect_person_membership on public.person;
create trigger protect_person_membership before update on public.person
  for each row execute procedure public.protect_person_membership();
revoke all on function public.protect_person_membership() from public;

create policy "members read gift rounds" on public.gift_round for select to authenticated
  using (public.is_family_member(family) or public.is_admin());
create policy "family managers create gift rounds" on public.gift_round for insert to authenticated
  with check (public.can_manage_family(family));
create policy "admins update gift rounds" on public.gift_round for update to authenticated using (public.is_admin());
create policy "admins delete gift rounds" on public.gift_round for delete to authenticated using (public.is_admin());

create policy "members read presents" on public.present for select to authenticated
  using (exists (select 1 from gift_round r where r.id = gift_round and (public.is_family_member(r.family) or public.is_admin())));
create policy "givers or managers create presents" on public.present for insert to authenticated
  with check (
    exists (select 1 from person p where p.id = giver and p.user_profile = auth.uid())
    or exists (select 1 from gift_round r where r.id = gift_round and public.can_manage_family(r.family))
  );
create policy "participants or managers update presents" on public.present for update to authenticated
  using (
    exists (select 1 from person p where p.user_profile = auth.uid() and p.id in (giver, receiver))
    or exists (select 1 from gift_round r where r.id = gift_round and public.can_manage_family(r.family))
  );
create policy "givers or managers delete presents" on public.present for delete to authenticated
  using (
    exists (select 1 from person p where p.id = giver and p.user_profile = auth.uid())
    or exists (select 1 from gift_round r where r.id = gift_round and public.can_manage_family(r.family))
  );

create or replace function public.validate_present_family()
returns trigger language plpgsql security definer set search_path = public
as $$
declare
  round_family bigint;
begin
  select family into round_family from gift_round where id = new.gift_round;
  if not exists (select 1 from person where id = new.giver and family = round_family)
    or not exists (select 1 from person where id = new.receiver and family = round_family)
    or (new.receiver_guess is not null and not exists (select 1 from person where id = new.receiver_guess and family = round_family)) then
    raise exception 'Gift participants must belong to the gift round family';
  end if;
  return new;
end
$$;

drop trigger if exists validate_present_family on public.present;
create trigger validate_present_family before insert or update on public.present
  for each row execute procedure public.validate_present_family();
revoke all on function public.validate_present_family() from public;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$ begin insert into profiles (id) values (new.id) on conflict (id) do nothing; return new; end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute procedure public.handle_new_user();
revoke all on function public.handle_new_user() from public;
